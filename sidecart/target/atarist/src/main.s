; Based on the SidecarTridge firmware loader (C) 2023-2025 by Diego Parrilla
; and atarist-stdoom's DOOM Accelerator stub.
;
; This image is served by the RP2040 at ROM4 ($FA0000). The ROTT
; Accelerator has no autostart: ROTT_ST.TOS finds the firmware itself and
; drives it over the cartridge bus. All the stub does is give TOS a valid
; cartridge header and, at boot, say whether the firmware is up, then the
; licence and where to get ROTT for the ST.
;
; Must fit in MD_HEADER_SIZE (1 KB): the status block follows at $FA0400.
; Offsets below must match sidecart/include/rott_md_protocol.h.

ROM4_ADDR		equ $FA0000
MD_HEADER_SIZE		equ $400
MD_READY_ADDR		equ (ROM4_ADDR + $F00A)	; MD_READY_OFFSET
MD_READY_MAGIC		equ $52			; 'R'
MD_RESULT_ADDR		equ (ROM4_ADDR + $F100)	; MD_RESULT_OFFSET
BOOT_READY_TIMEOUT	equ 250			; VBLs to wait for the RP
SCREEN_SIZE		equ (-4096)		; work area below the screen

	section

	org ROM4_ADDR

	dc.l $abcdef42			; magic number
first:
	dc.l 0				; CA_NEXT: no further programs
	dc.l $08000000 + pre_auto	; CA_INIT: after GEMDOS init, before boot
	dc.l 0				; CA_RUN: none
	dc.w GEMDOS_TIME		; time
	dc.w GEMDOS_DATE		; date
	dc.l end_pre_auto - pre_auto	; size
	dc.b "MDROTT",0
	even

pre_auto:
; Run from RAM rather than from the emulated cartridge (as stdoom does).
	move.w #2,-(sp)			; XBIOS Physbase
	trap #14
	addq.l #2,sp
	move.l d0,a2
	lea SCREEN_SIZE(a2),a2
	move.l a2,a3
	move.l #end_rom_code-start_rom_code,d6
	lea start_rom_code,a1
	addq.l #3,d6
	lsr.l #2,d6
	subq #1,d6
.copy:
	move.l (a1)+,(a2)+
	dbf d6,.copy
	jmp (a3)

start_rom_code:
	move.w #BOOT_READY_TIMEOUT,d6
.poll:
	cmpi.b #MD_READY_MAGIC,(MD_READY_ADDR).l
	beq.s .found
	move.w #37,-(sp)		; XBIOS Vsync
	trap #14
	addq.l #2,sp
	dbf d6,.poll

	pea msg_not_ready(pc)
	bra.s .print

.found:
	pea msg_ready(pc)
.print:
	pea banner_txt(pc)		; "ROTT Accelerator <version>"
	move.w #9,-(sp)			; GEMDOS Cconws
	trap #1
	addq.l #6,sp
	move.w #9,-(sp)			; then " ready" or " not responding"
	trap #1
	addq.l #6,sp
	pea msg_footer(pc)
	move.w #9,-(sp)
	trap #1
	addq.l #6,sp
	rts

; Boot banner. version.inc is generated by target/atarist/Makefile from
; version.txt at build time -- it defines banner_txt as
;   dc.b "ROTT Accelerator <version>",0
; so the banner always matches the shipped version. Each line fits the
; 40-column low-res screen.
	include version.inc
msg_ready:
	dc.b " ready",$d,$a,0
msg_not_ready:
	dc.b " not responding",$d,$a,0
msg_footer:
	dc.b "GPLv3 (c)2026 Neil Rackett",$d,$a,$d,$a
	dc.b "Get ROTT from neilrackett.com/atarist",$d,$a
	dc.b "and run ROTT_ST.TOS",$d,$a,0
	even
; Non-zero end marker: firmware.py trims trailing zero bytes and needs an
; even length.
	dc.w $FFFF

end_rom_code:
end_pre_auto:
	even
	dc.l 0

	ifgt (*-ROM4_ADDR)-MD_HEADER_SIZE
	fail "cartridge stub is larger than MD_HEADER_SIZE"
	endc
